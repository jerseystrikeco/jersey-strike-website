// Bundles PRICING-FORMULA.md and past-jobs/*.md into the quote function so Claude
// can read them. Netlify runs this on every deploy (see netlify.toml), so editing
// those files and redeploying is all it takes to update what Claude knows.
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const formula = readFileSync(new URL('PRICING-FORMULA.md', root), 'utf8');
const dir = new URL('past-jobs/', root);
const pastJobs = existsSync(dir)
  ? readdirSync(dir).filter((f) => f.endsWith('.md')).sort().map((file) => ({ file, text: readFileSync(new URL(file, dir), 'utf8') }))
  : [];
const out = `// GENERATED by scripts/build-knowledge.mjs. Don't edit; edit PRICING-FORMULA.md or past-jobs/ instead.
export const FORMULA = ${JSON.stringify(formula)};
export const PAST_JOBS = ${JSON.stringify(pastJobs, null, 1)};
`;
writeFileSync(new URL('netlify/functions/lib/knowledge.generated.mjs', root), out);
console.log(`knowledge: formula + ${pastJobs.length} past job(s)`);
